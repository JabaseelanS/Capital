let appWindow

function initWindow() {
    appWindow = new BrowserWindow({
        // fullscreen: true,
        width: 1000,
        height: 800,
        webPreferences: {
            nodeIntegration: true
        },
        icon: `file://${__dirname}/dist/packapill/assets/icons/hola-icon4.png`
    })

    // Electron Build Path
    appWindow.loadURL(
        url.format({
            pathname: path.join(__dirname, `/dist/packapill/index.html`),
            protocol: "file:",
            slashes: true
        })
    );

    // Initialize the DevTools.
    appWindow.webContents.openDevTools()

    appWindow.on('closed', function () {
        appWindow = null
    })
}
